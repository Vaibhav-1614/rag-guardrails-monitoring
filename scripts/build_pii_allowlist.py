"""Build configs/pii_allowlist.txt from the corpus.

Executive and director names ("/s/ Timothy D. Cook" signature lines), corporate phone numbers from
10-K cover pages, and company names are legitimate in questions about filings, but look like
PERSON / PHONE_NUMBER entities to a PII detector.

    python scripts/build_pii_allowlist.py
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / "src")]

from rag.companies import get_registry  # noqa: E402
from rag.corpus import load_corpus  # noqa: E402

# Well-known short forms that differ from the signature-page spelling.
MANUAL = """
tim cook
satya nadella
sundar pichai
andy jassy
jeff bezos
mark zuckerberg
jensen huang
elon musk
jamie dimon
darren woods
joaquin duato
kevan parekh
amy hood
susan li
colette kress
vaibhav taneja
jeremy barnum
""".split("\n")

_SIG = re.compile(r"/s/[ \t]+([^\n/]{3,80})")
_ROLE_WORDS = {
    "chief", "director", "senior", "executive", "president", "chair", "chairman", "vice", "corporate", "principal",
    "global", "treasurer", "controller", "lead", "independent", "general", "officer", "dated", "and", "of", "the",
    "board", "date", "evp", "svp", "cfo", "ceo", "accounting", "financial",
}
_NAME_TOKEN = re.compile(r"^(?:[A-Z]\.|[A-Z][A-Za-z'\-]+\.?)$")


def clean_name(raw: str) -> str | None:
    toks: list[str] = []
    for tok in raw.replace(",", " ").split():
        if tok.lower().strip(".") in _ROLE_WORDS or re.match(r"\d", tok) or not _NAME_TOKEN.match(tok):
            break
        toks.append(tok)
    if len(toks) < 2 or len(toks) > 4 or all(len(t.rstrip(".")) == 1 for t in toks):
        return None
    return " ".join(t.title() if t.isupper() and len(t) > 2 else t for t in toks)
_PHONE = re.compile(r"\(\d{3}\)\s?\d{3}[-\s]\d{4}|\b\d{3}[-.]\d{3}[-.]\d{4}\b")


def main() -> None:
    corpus = load_corpus()
    names: set[str] = set()
    phones: set[str] = set()
    for c in corpus.chunks:
        for m in _SIG.finditer(c.text):
            if "LLP" in m.group(1) or "&" in m.group(1):
                continue
            name = clean_name(m.group(1))
            if name:
                names.add(name)
        if c.section in ("Cover", "Contents", "Item 5", "Item 15", "Item 16") or "telephone" in c.text.lower():
            phones.update(_PHONE.findall(c.text))
    reg = get_registry()
    companies = sorted({info["name"] for info in reg.covered.values()} | {a for info in reg.covered.values() for a in info.get("aliases", [])})
    lines = ["# Generated by scripts/build_pii_allowlist.py. Matching is case/punctuation-insensitive.",
             "# Executives and directors (10-K signature pages)"]
    lines += sorted(names, key=str.lower) + ["", "# Well-known short forms"] + sorted(n.strip() for n in MANUAL if n.strip())
    lines += ["", "# Company names"] + companies + ["", "# Corporate phone numbers (10-K cover pages)"] + sorted(phones)
    out = ROOT / "configs" / "pii_allowlist.txt"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(names)} names, {len(phones)} phone numbers -> {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
